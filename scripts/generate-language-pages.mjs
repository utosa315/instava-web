import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const template = fs.readFileSync(path.join(projectRoot, "index.html"), "utf8");
const localeSource = fs.readFileSync(path.join(projectRoot, "landing-locales.js"), "utf8");
const context = { window: {} };
vm.runInNewContext(localeSource, context);

const copy = {
  ja: {
    title: "インスタの写真・動画・リールを画質を落とさず保存｜Instava",
    description: "インスタの写真・動画・リールを画質を落とさず保存。起動時やアプリ復帰時に突然の全画面動画広告で操作を止めません。毎日1URLはそのまま保存、2URL目は選んでリワード広告を視聴。",
    locale: "ja_JP"
  },
  en: {
    title: "Instava | Save Instagram photos, videos, and Reels",
    description: "Save public Instagram photos, videos, and Reels without losing quality. No surprise full-screen video when opening or returning to the app. Save one URL daily without one; choose a rewarded ad for a second.",
    locale: "en_US"
  },
  ...Object.fromEntries(Object.entries(context.window.INSTAVA_LANDING_LOCALES).map(([language, value]) => [language, {
    title: value.title,
    description: `${value.intro} ${value.ads[1]}`,
    locale: ({ ar: "ar_AR", de: "de_DE", es: "es_419", fr: "fr_FR", hi: "hi_IN", id: "id_ID", it: "it_IT", ko: "ko_KR", pt: "pt_BR", th: "th_TH", tr: "tr_TR", vi: "vi_VN", zh: "zh_TW" })[language]
  }]))
};

function escapeAttribute(value) {
  return value.replaceAll("&", "&amp;").replaceAll('"', "&quot;");
}

for (const [language, metadata] of Object.entries(copy)) {
  const canonical = `https://instava.tardigrader.com/${language}/`;
  let html = template
    .replace("<!DOCTYPE html>", "<!DOCTYPE html>\n<!-- Generated by scripts/generate-language-pages.mjs. -->")
    .replace(/<html lang="[^"]+">/, `<html lang="${language}">`)
    .replace(/<link rel="canonical" href="[^"]+">/, `<link rel="canonical" href="${canonical}">`)
    .replace(/<link rel="preload" href="\/assets\/app-select-[^"]+"/, `<link rel="preload" href="/assets/app-select-${language}.webp"`)
    .replace(/<meta property="og:url" content="[^"]+">/, `<meta property="og:url" content="${canonical}">`)
    .replace(/<meta property="og:image:alt" content="[^"]+">/, `<meta property="og:image:alt" content="Instava app icon">`)
    .replace(/(<title[^>]*>)[\s\S]*?(<\/title>)/, `$1${metadata.title}$2`)
    .replace(/(<meta name="description"[\s\S]*?\scontent=")[^"]*(">)/, `$1${escapeAttribute(metadata.description)}$2`)
    .replace(/(<meta property="og:title"[^>]*\scontent=")[^"]*(">)/, `$1${escapeAttribute(metadata.title)}$2`)
    .replace(/(<meta property="og:description"[^>]*\scontent=")[^"]*(">)/, `$1${escapeAttribute(metadata.description)}$2`)
    .replace(/(<meta property="og:locale"[^>]*\scontent=")[^"]*(">)/, `$1${metadata.locale}$2`)
    .replace(/(<meta name="twitter:title"[^>]*\scontent=")[^"]*(">)/, `$1${escapeAttribute(metadata.title)}$2`)
    .replace(/(<meta name="twitter:description"[^>]*\scontent=")[^"]*(">)/, `$1${escapeAttribute(metadata.description)}$2`)
    .replace(/("description": ")[^"]*(")/, `$1${metadata.description.replaceAll('"', '\\"')}$2`);

  const directory = path.join(projectRoot, language);
  fs.mkdirSync(directory, { recursive: true });
  fs.writeFileSync(path.join(directory, "index.html"), html);
}

console.log(`Generated ${Object.keys(copy).length} language pages.`);
